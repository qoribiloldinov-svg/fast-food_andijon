/* --- UPGRADED MULTI-STEP CHECKOUT SYSTEM LOGIC --- */
function initCheckoutSystem() {
    const overlay = document.getElementById('checkoutModalOverlay');
    const closeBtn = document.getElementById('checkoutClose');
    const nextBtn = document.getElementById('chkNextBtn');
    const backBtn = document.getElementById('chkBackBtn');

    if(!overlay) return;

    closeBtn.addEventListener('click', closeCheckoutModal);
    overlay.addEventListener('click', (e) => {
        if(e.target === overlay) closeCheckoutModal();
    });

    // Order type card selection
    document.getElementById('cardDelivery').addEventListener('click', () => {
        setOrderType('delivery');
    });
    document.getElementById('cardPickup').addEventListener('click', () => {
        setOrderType('pickup');
    });

    // Uzbekistan phone prefix formatting protection
    ['delPhone', 'pickPhone'].forEach(id => {
        const input = document.getElementById(id);
        if(input) {
            input.addEventListener('input', (e) => {
                if(!e.target.value.startsWith('+998')) {
                    e.target.value = '+998 ';
                }
            });
        }
    });

    nextBtn.addEventListener('click', handleCheckoutNext);
    backBtn.addEventListener('click', handleCheckoutBack);
}

function openCheckoutModal() {
    checkoutState.step = 1;
    checkoutState.orderType = 'delivery';
    renderCheckoutStep();
    document.getElementById('checkoutModalOverlay').classList.add('open');
}

function closeCheckoutModal() {
    document.getElementById('checkoutModalOverlay').classList.remove('open');
}

function setOrderType(type) {
    checkoutState.orderType = type;
    if(type === 'delivery') {
        document.getElementById('cardDelivery').classList.add('selected');
        document.getElementById('cardPickup').classList.remove('selected');
        document.getElementById('deliveryFormView').classList.add('active');
        document.getElementById('pickupFormView').classList.remove('active');
    } else {
        document.getElementById('cardPickup').classList.add('selected');
        document.getElementById('cardDelivery').classList.remove('selected');
        document.getElementById('pickupFormView').classList.add('active');
        document.getElementById('deliveryFormView').classList.remove('active');
    }
}

function handleCheckoutNext() {
    if(checkoutState.step === 1) {
        // Validate selection and go to Step 2
        checkoutState.step = 2;
        renderCheckoutStep();
    } else if(checkoutState.step === 2) {
        // Validate form fields
        if(!validateForm()) return;
        saveFormData();
        checkoutState.step = 3;
        renderCheckoutStep();
    } else if(checkoutState.step === 3) {
        // Confirm order -> go to Step 4 (Success)
        checkoutState.step = 4;
        renderCheckoutStep();
        cart = []; // clear cart after successful order
        saveAndRenderCart();
    } else if(checkoutState.step === 4) {
        closeCheckoutModal();
    }
}

function handleCheckoutBack() {
    if(checkoutState.step > 1 && checkoutState.step < 4) {
        checkoutState.step--;
        renderCheckoutStep();
    }
}

function validateForm() {
    if(checkoutState.orderType === 'delivery') {
        const name = document.getElementById('delName').value.trim();
        const phone = document.getElementById('delPhone').value.trim();
        const street = document.getElementById('delStreet').value.trim();
        const house = document.getElementById('delHouse').value.trim();

        if(!name || phone.length < 13 || !street || !house) {
            alert(currentLang === 'uz' ? "Iltimos, barcha majburiy maydonlarni to'ldiring va telefon raqamini to'g'ri kiriting!" : "Please fill in all required fields and enter a valid phone number!");
            return false;
        }
    } else {
        const name = document.getElementById('pickName').value.trim();
        const phone = document.getElementById('pickPhone').value.trim();
        if(!name || phone.length < 13) {
            alert(currentLang === 'uz' ? "Iltimos, ismingiz va telefon raqamingizni kiriting!" : "Please enter your name and phone number!");
            return false;
        }
    }
    return true;
}

