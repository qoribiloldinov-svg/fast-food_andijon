function addToCart(name, price, image = 'https://images.unsplash.com/photo-1568901346375-23c9450c58cd?auto=format&fit=crop&w=700&q=80') {
    const existing = cart.find(item => item.name === name);
    if (existing) {
        existing.qty += 1;
    } else {
        cart.push({ name, price, qty: 1, image });
    }
    saveAndRenderCart();
    showToast();
}

function updateQty(name, change) {
    const item = cart.find(i => i.name === name);
    if(item) {
        item.qty += change;
        if(item.qty <= 0) {
            cart = cart.filter(i => i.name !== name);
        }
    }
    saveAndRenderCart();
}

function saveAndRenderCart() {
    localStorage.setItem('crush_cart', JSON.stringify(cart));
    updateCartUI();
}

function updateCartUI() {
    const container = document.getElementById('cartItemsContainer');
    const badge = document.getElementById('cartBadge');
    const totalPriceEl = document.getElementById('cartTotalPrice');
    if(!container) return;
    
    container.innerHTML = '';
    let totalCount = 0;
    let totalPrice = 0;

    cart.forEach(item => {
        totalCount += item.qty;
        totalPrice += item.price * item.qty;
        container.innerHTML += `
            <div class="cart-item">
                <div class="cart-item-info">
                    <h4>${item.name}</h4>
                    <span>${item.price.toLocaleString()} UZS</span>
                </div>
                <div class="cart-item-controls">
                    <button class="qty-btn" onclick="updateQty('${item.name}', -1)">-</button>
                    <span>${item.qty}</span>
                    <button class="qty-btn" onclick="updateQty('${item.name}', 1)">+</button>
                </div>
            </div>
        `;
    });

    badge.textContent = totalCount;
    totalPriceEl.textContent = totalPrice.toLocaleString() + " UZS";
}

